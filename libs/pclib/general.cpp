void Beep (void)
{
    sound (440);
    delay (25);
    nosound ();
    delay (25);
    sound (660);
    delay (25);
    nosound ();
    delay (25);
    sound (440);
    delay (25);
    nosound ();
}

//==============================================================================

void Quit (errorcode error)
{
    exit (error);
}

