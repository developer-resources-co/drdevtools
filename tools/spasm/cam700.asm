.CODE

	; need offset into operand_bytes (which is reset every assemble instruction)
_CAM_AD	PROC	NEAR

				; al,ah,bx = 1st,2nd,3rd,4th chars
				; cl,ch,dl,dh = last 4 chars
	MOV	AX,WORD PTR [PARAM_FIELD+SI]
	MOV	BX,WORD PTR [PARAM_FIELD+SI+2]
	MOV	DX,WORD PTR [PARAM_FIELD+DI-1]
	MOV	CX,WORD PTR [PARAM_FIELD+DI-3]

	cmp	ax,'A'		; A, ?
	je	@@Src_A
	cmp	ax,'X'		; X, ?
	je	@@Src_X
	cmp	ax,'Y'		; Y, ?
	je	@@Src_y

	cmp	ax,'X('		; (X
	jne	@@Not_Src_X_
	cmp	bx,'+)'		; (X|)+ ?
	je	@@Src_X__
	cmp	bx,')'		; (X|), ?
	je	@@Src_X_
@@Not_Src_X_:

	cmp	ax,'Y('		; (Y
	jne	@@Not_Src_Y_
	cmp	bx,')'		; (Y) ?
	jne	@@Not_Src_Y_
	mov	al,16
	jmp	@@Calc_Src_Done
@@Not_Src_Y_:

	cmp	dx,'PS'		; SP ?
	je	@@Src_SP

	cmp	al,'['
	jne	@@Not_Src_Double_Indirect

	cmp	dx,']X'		; [dp+x] ?
	jne	@@Not_Src_dp_X
	cmp	ch,'+'
	jne	@@Not_Src_dp_X

	mov	[PARAM_FIELD+DI-2],0	; zero "+" for exp. parser
	add	si,1		; past opening "["
	call	parse_exp
	mov	word ptr [operand_bytes],cx

	mov	al,12
	jmp	@@Calc_Src_Done
@@Not_Src_dp_X:

	cmp	dx,'Y+'		; [dp]+Y ?
	jne	@@Not_Src_dp_Y
	cmp	ch,']'
	jne	@@Not_Src_dp_Y

	mov	[PARAM_FIELD+DI-2],0	; zero "[" for exp. parser
	add	si,1		; past opening "["
	call	parse_exp
	mov	word ptr [operand_bytes],cx

	mov	al,13
	jmp	@@Calc_Src_Done
@@Not_Src_dp_Y:
@@Not_Src_Double_Indirect:

	cmp	dx,'X+'		; dp+x or !abs+x
	jne	@@Not_Plus_X

	mov	[PARAM_FIELD+DI-1],0	; zero out "+" for exp. parser
	call	parse_exp
	; subtract direct page value
	mov	word ptr [operand_bytes],cx

	cmp	cx,0100h
	jnc	@@Absolute_Plus_X
	;----- dp+x
	mov	al,7
	jmp	@@Calc_Src_Done

@@Absolute_Plus_X:
	mov	al,10
	jmp	@@Calc_Src_Done
@@Not_Plus_X:

	cmp	dx,'Y+'		; dp+y or !abs+y
	jne	@@Not_Plus_Y

	mov	[PARAM_FIELD+DI-1],0	; zero out "+" for exp. parser
	call	parse_exp
	; subtract direct page value
	mov	word ptr [operand_bytes],cx

	cmp	cx,0100h
	jnc	@@Absolute_Plus_Y
	;----- dp+y
	mov	al,8
	jmp	@@Calc_Src_Done

@@Absolute_Plus_Y:
	mov	al,11
	jmp	@@Calc_Src_Done
@@Not_Plus_Y:

	cmp	al,'#'
	jne	@@Not_Immediate

	add	si,1			; skip "#"
	call	parse_exp
	mov	byte ptr [operand_bytes],cl	; only 8-bit values!

	mov	al,15
	jmp	@@Calc_Src_Done
@@Not_Immediate:

	;----- Just evaluate expression
	call	parse_exp
	mov	word ptr [operand_bytes],cx

	cmp	cx,0100h
	jnc	@@Absolute
	;----- direct page
	mov	al,6
	jmp	@@Calc_Src_Done

@@Absolute:
	mov	al,9
	jmp	@@Calc_Src_Done

	mov	al,0
	jmp	@@Calc_Src_Done

@@Src_SP:
	mov	al,14
	jmp	@@Calc_Src_Done
@@Src_X__:
	mov	al,5
	jmp	@@Calc_Src_Done
@@Src_X_:
	mov	al,4
	jmp	@@Calc_Src_Done
@@Src_A:
	mov	al,1
	jmp	@@Calc_Src_Done
@@Src_X:
	mov	al,2
	jmp	@@Calc_Src_Done
@@Src_Y:
	mov	al,3
	jmp	@@Calc_Src_Done


@@Calc_Src_Done:
	ret

_CAM_AD	ENDP

;------------------------------------------------------------------------------
; Inputs:
; Outputs:
;   	dl = source addressing code(0 = not found)
;	dh = dest addressing mode
;?	bl:cx = operand value
;------------------------------------------------------------------------------

CAM_AD	PROC	NEAR		;CHECK ADDRESSING MODE FOR "a" & "d" OPERATORS
				;SOURCE AM=DL, DEST AM=DH
				;OPERAND VALUE IN BL:CX

	PUSH	si		; save table pointer for this opcode

	mov	am,0

	;for testing only
	mov	word ptr [operand_bytes],0

	call	pos_dst
	push	si
	push	di

	call	pos_src
	mov	[param_field+di+1],0	; zero terminate string

	call	_CAM_AD
	mov	SAM,al

@@Calc_Dest:
	pop	di
	pop	si	; dest already zero-terminated (end of string)

	call	_CAM_AD
	mov	DAM,al

@@DoForwardReference:
;;	mov	dl,AM16
;;	or	dl,dl
;;	jnz	@@CAD15
;;	mov	dl,AM8
;;	jmp	@@CAD15


@@CAD15:
	pop	si

	mov	dx,AM

	RET

CAM_AD	ENDP

