	JMP	GROUP22

P_CMP:	MOV	OPCMASK,0B000H		;CMP

	CALL    POS_DST			;CMPA/CMPI KLUDGE
	JC	P_CMP1
	CALL	CAM_A
	JNC	P_CMPA
P_CMP1:	CALL	POS_SRC
	JC	P_CMP2
	CALL	CAM_I
	JNC	P_CMPI

P_CMP2:	JMP	GROUP4

P_CMPA:	MOV	OPCMASK,0B000H		;CMPA
	JMP	GROUPA

P_CMPI:	MOV	OPCMASK,0C00H		;CMPI
	JMP	GROUP5

P_CMPM:	CALL	POS_DST			;CMPM
	JC	PCERR57
	CALL	CAM_EA
	JC	PCERR9
	CMP	AMQR,3
	JNZ	PCERR9
	MOV	AH,MOD_REG
	AND	AH,7
	SHL	AH,1
	OR	AH,0B1H
	MOV	AL,SEYES
	MOV	OPCMASK,AX
	CALL	POS_SRC
	CALL	CAM_EA
	JC	PCERR9
	CMP	AMQR,3
	JNZ	PCERR9
	MOV	AL,MOD_REG
	AND	AL,0FH
	XOR	AH,AH
	OR	AX,OPCMASK
	JMP	STORE_WORD

PCERR9:	MOV	AX,9		;ILLEGAL A.M.
	JMP	ERROR

PCERR57:
	MOV	AX,57		;NO DST OPR.
	JMP	ERROR

PARSE_C	ENDP


PARSE_D	PROC	NEAR

	CMP	AL,'B'		;DBcc?
	JNZ	P_D6
	CMP	CL,'.'
	JNZ	P_D1
	XOR	CL,CL
P_D1:	OR	CL,CL
	JZ	P_D2

	OR	CH,CH
	JZ	P_D2
	CMP	CH,'.'
	JNZ	P_D99
	CMP	DL,'W'
	JNZ	P_D99

P_D2:	MOV	AL,AH
	MOV	AH,CL
	MOV	DL,1
	CMP	AX,'AR'		;DBRA?
	JZ	P_DBcc
	CALL	CCC
	JMP	P_DBcc

P_D6:	CMP	AX,'VI'		;DIVx?
	JNZ	P_D99
	CMP	SEYES,40H
	JNZ	P_D99
	CMP	CX,'S'
	JZ	P_DIVS
	CMP	CX,'.S'
	JZ	P_DIVS
	CMP	CX,'U'
	JZ	P_DIVU
	CMP	CX,'.U'
	JZ	P_DIVU

P_D99:	JMP	PARSE_PSEUDO

P_DBcc: CMP     DL,10H
        JNB     P_D99
	MOV 	CCMASK,DL
	CALL	POS_SRC
	CALL	CAM_D
	MOV	AX,47
	JC	PDERR
	CALL	POS_DST
	MOV	AX,57
	JC	PDERR
	CALL	CAM_R
	MOV	AX,50C8H
	OR	AH,CCMASK
	OR	AL,DREG
	CALL	STORE_WORD
	MOV	AX,RDW
	JMP	STORE_WORD

P_DIVS:	MOV	OPCMASK,81C0H
	JMP	GROUP9

P_DIVU:	MOV	OPCMASK,80C0H
	JMP	GROUP9

PDERR:	JMP	ERROR

