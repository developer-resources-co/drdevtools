PARSE_A	PROC	NEAR

	OR	CL,CL
	JZ	P_A1
	CMP	CL,'.'
	JNZ	P_A3
P_A1:	CMP	AX,'LS'		;ASL?
	JZ	P_ASL
	CMP	AX,'RS'		;ASR?
	JZ	P_ASR
	CMP	AX,'DD'		;ADD?
        JZ	PADD
	CMP	AX,'DN'		;AND?
	JZ	PAND
	JMP	P_A3

PADD:	JMP	P_ADD
PAND:	JMP	P_AND

P_A3:	CMP	CX,'I'
	JZ	P_A3X
	CMP	CX,'.I'		;ANDI/ADDI
	JNZ	P_A4
P_A3X:	CMP	AX,'DN'
	JZ	PANDI
	CMP	AX,'DD'
	JZ	PADDI
	JMP	P_A4

PANDI:	JMP	P_ANDI
PADDI:	JMP	P_ADDI

P_A4:	CMP	AX,'CB'
	JNZ	P_A5
	CMP	CX,'D'
	JZ	P_ABCD
	CMP	CX,'.D'
	JZ	P_ABCD
P_A5:	CMP	AX,'DD'
	JNZ	P_A6
	CMP	CX,'X'
	JZ	P_ADDX
	CMP	CX,'.X'
	JZ	P_ADDX
	CMP	CX,'Q'
	JZ	P_ADDQ
	CMP	CX,'.Q'
	JZ	P_ADDQ
	CMP	CX,'A'
	JZ	P_ADDA
	CMP	CX,'.A'
	JZ	P_ADDA
P_A6:

	JMP	PARSE_PSEUDO

P_ASL:	MOV	SOPC1,0E1H		;ASL
	MOV	SOPC2,0E100H
	JMP	SHIFT_SPLIT
P_ASR:	MOV	SOPC1,0E0H		;ASR
	MOV	SOPC2,0E000H
	JMP	SHIFT_SPLIT

P_ABCD:	MOV	OPCMASK,0C100H		;ABCD
	JMP	GROUP1

P_AND:	MOV	OPCMASK,0C000H		;AND

	CALL	POS_SRC			;ANDI KLUDGE
	JC	P_AND1
	CALL	CAM_I
	JNC	P_ANDI

P_AND1:	JMP	GROUP3

P_ADDI:	MOV	OPCMASK,600H		;ADDI
	JMP	GROUP5

P_ANDI:	MOV	OPCMASK,200H		;ANDI
	JMP	GROUP5

P_ADDX:	MOV	AX,0D100H		;ADDX
	OR	AL,SEYES
	MOV	OPCMASK,AX
	JMP	G1_0

P_ADDQ:	MOV	OPCMASK,5000H		;ADDQ
	JMP	GROUP6

P_ADDA:	MOV	OPCMASK,0D000H  	;ADDA
	JMP	GROUPA

P_ADD:	MOV	OPCMASK,0D000H		;ADD

	CALL	POS_DST			;ADDI/ADDA KLUDGE
	JC	P_ADD1
	CALL	CAM_A
	JNC	P_ADDA
P_ADD1:	CALL	POS_SRC
	JC	P_ADD2
	CALL	CAM_I
	JNC	P_ADDI

P_ADD2:	JMP	GROUP3

PARSE_A	ENDP


PARSE_B	PROC	NEAR

	CMP	BP,'S.'
	JZ	P_Bcc
	OR	CL,CL
	JZ	P_Bcc

	OR	CH,CH
	JZ	P_B1
	CMP	CH,'.'
	JNZ	P_B99
P_B1:	CMP	AX,'HC'		;BCHG?
	JNZ	P_B2
	CMP	CL,'G'
	JZ	P_BCHG
	JMP	P_B99
P_B2:	CMP	AX,'LC'		;BCLR?
	JNZ	P_B3
	CMP	CL,'R'
	JZ	P_BCLR
	JMP	P_B99
P_B3:	CMP	CL,'T'
	JNZ	P_B99
	CMP	AX,'ES'		;BSET?
	JZ	P_BSET
	CMP	AX,'ST'
	JZ	P_BTST

P_B99:	JMP	PARSE_PSEUDO

P_Bcc:	XOR	DL,DL
	CMP	AX,'AR'
	JZ	P_Bcc1
	INC	DL
	CMP	AX,'RS'
	JZ	P_Bcc1
	CALL	CCC
	CMP	DL,0FH
	JA	P_B99
	CMP	DL,2
	JB	P_B99
P_Bcc1:	MOV	AX,6000H
	OR	AH,DL
	MOV	OPCMASK,AX
	CMP	BP,'S.'
	JZ	P_Bcc2
	CALL	POS_SRC
	CALL	CAM_R
	MOV	AX,OPCMASK
	CALL	STORE_WORD
	MOV	AX,RDW
	JMP	STORE_WORD

P_Bcc2:	CALL	POS_SRC
	CALL	CAM_RS
	MOV	AX,OPCMASK
	MOV	AL,RDB
	JMP	STORE_WORD

P_BCHG:	MOV	OPCMASK,40H
	JMP	BIT_SPLIT

P_BCLR:	MOV	OPCMASK,80H
	JMP	BIT_SPLIT

P_BSET:	MOV	OPCMASK,0C0H
	JMP	BIT_SPLIT

P_BTST:	MOV	OPCMASK,0
	JMP	BIT_SPLIT

PARSE_B	ENDP


