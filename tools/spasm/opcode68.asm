ASM_EA	PROC	NEAR		;GO FOR IT!

	MOV	AX,OPCMASK
	OR	AL,MOD_REG
	CALL	STORE_WORD

ASM_1:	CMP	MOD_REG,111001B
	JZ	ASM_2
	CMP	MOD_REG,111100B
	JZ	ASM_3

	CMP	MOD_REG,111010B
	JZ	ASM_4
	CMP	MOD_REG,111011B
	JZ	ASM_4
	AND	MOD_REG,38H
	CMP	MOD_REG,101000B
	JZ	ASM_4
	CMP	MOD_REG,110000B
	JZ	ASM_4
	RET

ASM_2:	MOV	AX,XW1
	CALL	STORE_WORD
	MOV	AX,XW2
	JMP	STORE_WORD

ASM_3:	CMP	SEYES,80H
	JZ	ASM_2

ASM_4:	MOV	AX,XW1
	JMP	STORE_WORD

ASM_EA	ENDP

