PARSE_MNE	PROC	NEAR	;GET FIRST LETTER AND BRANCH ACCORDINGLY

	AND	SDB2,NOT 41H	;ERROR ALERT ON!  PARSE PSEUDO OFF!

	MOV	BL,[MNE_FIELD]			;FIRST PARSE AS A MNEMONIC
	SUB	BL,'A'
	CMP	BL,'Z'
	JA	P1
	XOR	BH,BH
	SHL	BX,1
	MOV	AX,WORD	PTR [MNE_FIELD+1]
	MOV	CX,WORD PTR [MNE_FIELD+3]
	MOV	DX,WORD PTR [MNE_FIELD+5]

	MOV	SEYES,40H
	MOV	DI,MNE_LEN
	SUB	DI,2
	XOR	BP,BP
	CMP	[MNE_FIELD+DI],'.'
	JNZ	P0
	MOV	BP,WORD PTR [MNE_FIELD+DI]
	MOV	SEYES,0
	CMP	BP,'B.'
	JZ	P0
	MOV	SEYES,40H
	CMP	BP,'W.'
	JZ	P0
	MOV	SEYES,80H
	CMP	BP,'L.'
	JZ	P0
	CMP	BX,2
	JNZ	P1
	CMP	BP,'S.'
	JNZ	P1
P0:	JMP	[PARSE_TABLE+BX]

P1:	JMP	PARSE_PSEUDO			;THEN TRY PARSING AS PSEUDO-OP

PARSE_MNE	ENDP

