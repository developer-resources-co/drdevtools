	{
	kbhit();
	}


rastGraphPort*
	Mix( rastGraphPort* pict1, rastGraphPort* pict2, rastGraphPort* stencil )
	{
	rastGraphPort* pict = new rastGraphPort( 320, 200, 256 );

	for ( int y=0; y<pict1->GetHeight(); ++y )
		{
		for ( int x=0; x<pict1->GetWidth(); ++x )
			{
			point p(x,y);
			colorMapIndex col =
				stencil->GetPixelIndex( p ) ?
				pict2->GetPixelIndex( p ) :
				pict1->GetPixelIndex( p );
			pict->SetColorIndex( col );
			pict->PutPixel( p );
			}
		}

	// Create a new palette!
	return pict;
	}


iffWrite& operator<<( iffWrite& s, Picture& pict )
	{
	assert( pict.oldBODY || pict.newBODY );
	assert( pict.newBODY );		// for testing only

	if ( pict.oldBODY )
		s.NewForm( tagILBM );
	else
		s.NewForm( tagPBM );

	s << *(pict.BitmapHeader);
	s << *(pict.ColorMap);

	s << iffANNO( "Generated by TransABM.  Copyright 1994 Cave Logic Studios.  All Rights Reserved." );

	if ( pict.oldBODY )
		s << *(pict.oldBODY);
	else
		s << *(pict.newBODY);

	return s;
	}

