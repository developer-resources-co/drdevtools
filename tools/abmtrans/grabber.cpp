void
	main (int argc,char *argv[])
	{
	GetInput( argc, argv );
	ctrlbrk( ctrlBreakHandler );

	screen = new screenGraphPort( 320, 200, 256 );
	assert( screen );

	ifstream* input;

	input = new ifstream( argv[1], ios::in | ios::binary );
	assert( input );
	pict1 = new Picture( *input );
	delete input;

	input = new ifstream( argv[2], ios::in | ios::binary );
	assert( input );
	Picture* pict2 = new Picture( *input );
	delete input;

	input = new ifstream( argv[3], ios::in | ios::binary );
	assert( input );
	Animation* animStencil = new Animation( *input );
	delete input;
//	FlipBook( animStencil );

	int nFrame = 1;
	for ( Animation* a1 = animStencil; a1; a1 = a1->pNext, ++nFrame, check_ctrl_break() )
		{
		char outputLBM[ 128 ];
		Picture* pictMix = new Picture();
		assert( pictMix );

		pictMix->ColorMap = pict1->ColorMap;
		pictMix->BitmapHeader = pict1->BitmapHeader;
		pictMix->BitmapHeader->compression = 0;
		pictMix->newBODY = new pbmBODY( Mix( pict1->rp, pict2->rp, a1->rp ) );
		pictMix->newBODY->bmhd = pictMix->BitmapHeader;

		DisplayRastPort( pictMix->newBODY->rp );

		sprintf( outputLBM, "test%04d.lbm", nFrame );
		ofstream of( outputLBM );
		iffWrite* output = new iffWrite( of );
		assert( output );

		*output << *pictMix;
		delete output;

		delete pictMix->newBODY->rp;

		pictMix->ColorMap = NULL;
		pictMix->BitmapHeader = NULL;

		delete pictMix;
		}

	delete pict2;
	delete pict1;
	delete animStencil;
	delete screen;

	Quit();
	}
